#!/usr/bin/env python3
"""Writes zstd_test_vector.h, the frame validate_zstd decodes at boot.

The input is generated, not stored: zstd_test_input() in zstd_kernel.c rebuilds
it with the same generator, so keep the two in sync.

Usage: python3 make_test_vector.py  (needs the zstd command line tool)
"""
import os
import subprocess
import tempfile

# Over one 128KB zstd block, so the frame holds more than one block
SIZE = 160 * 1024
LEVEL = 15  # bake's __CHEF_ZSTD_COMPRESSION_LEVEL


def generate():
    state = 0x12345678

    def rnd():
        nonlocal state
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        return state >> 16

    out = bytearray()
    while len(out) < SIZE:
        if len(out) < 256 or rnd() % 8 == 0:
            # short run of literals from a 16 letter alphabet
            for _ in range(1 + rnd() % 16):
                out.append(ord("a") + rnd() % 16)
        else:
            # match against earlier output, may overlap itself
            length = 32 + rnd() % 480
            offset = 1 + rnd() % min(len(out), 65536)
            for _ in range(length):
                out.append(out[len(out) - offset])
    return bytes(out[:SIZE])


def main():
    data = generate()
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "input.bin")
        with open(path, "wb") as f:
            f.write(data)
        # a file input (not stdin) so the frame header carries the content size
        frame = subprocess.run(["zstd", f"-{LEVEL}", "--check", "-q", "-c", path],
                               check=True, capture_output=True).stdout
        version = subprocess.run(["zstd", "--version"], check=True, capture_output=True,
                                 text=True).stdout.strip()

    lines = [
        "/* Generated by make_test_vector.py, do not edit.",
        f" * {version}",
        f" * zstd -{LEVEL} --check of {SIZE} generated bytes */",
        "#ifndef __ZSTD_TEST_VECTOR_H__",
        "#define __ZSTD_TEST_VECTOR_H__",
        "",
        f"#define ZSTD_TEST_CONTENT_SIZE {SIZE}",
        "",
        "static const unsigned char zstd_test_frame[] = {",
    ]
    for i in range(0, len(frame), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in frame[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "zstd_test_vector.h")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{out}: {len(frame)} byte frame for {SIZE} bytes")


if __name__ == "__main__":
    main()
