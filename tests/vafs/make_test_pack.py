#!/usr/bin/env python3
"""Writes the generated VaFS test packs that validate_vafs (kernel/drivers/vafs.c) mounts.

bake's packs are too small to cross block boundaries, and libvafs' mkvafs always compresses with
aplib or brieflz, which the kernel does not decode. So this writes packs directly, with small
8KB data blocks so reads cross block boundaries in both streams:

    /big.bin              300000 generated bytes (37 data blocks)
    /many/f000.txt ...    400 small files, enough descriptors to fill more than one 8KB block
    /deep/a/b/c/leaf.txt  "leaf\\n"
    /link                 symlink to big.bin

The kernel rebuilds the same content to compare against, keep the two in sync.

Usage: python3 make_test_pack.py raw|zstd <out.pak>
The raw pack has no filter feature and libvafs' own unmkvafs can extract it, which checks this
writer against the reference implementation. The zstd pack marks its blocks with bake's filter
feature and needs the zstd command line tool.
"""
import struct
import subprocess
import sys

VAFS_MAGIC = 0x3144524D
VAFS_VERSION = 0x00010000
STREAM_MAGIC = 0x314D5356
BLOCK_SIZE = 8 * 1024
FILTER_GUID = bytes([0x91, 0x5D, 0xC2, 0x99, 0x99, 0xFA, 0x71, 0x4A,
                     0x9C, 0xB5, 0x96, 0x1A, 0xA9, 0x3D, 0xDF, 0xBB])
OVERVIEW_GUID = bytes.fromhex("522338b1c74bd245b759615a42d4452a")
TYPE_FILE, TYPE_DIRECTORY, TYPE_SYMLINK = 1, 2, 3


def big_file():
    # same generator as vafs_test_byte() in the kernel
    state = 0x12345678
    out = bytearray(300000)
    for i in range(len(out)):
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = state >> 16 & 0xFF
    return bytes(out)


def small_file(n):
    return (f"file {n:03d}\n" * (n % 5 + 1)).encode()


def tree():
    """{name: bytes | dict | ("link", target)}, in the order entries are written"""
    return {
        "big.bin": big_file(),
        "many": {f"f{n:03d}.txt": small_file(n) for n in range(400)},
        "deep": {"a": {"b": {"c": {"leaf.txt": b"leaf\n"}}}},
        "link": ("link", "big.bin"),
    }


def crc_table():
    table = []
    for i in range(256):
        value = i << 24
        for _ in range(8):
            value = (value << 1 ^ 0x04C11DB7 if value & 0x80000000 else value << 1) & 0xFFFFFFFF
        table.append(value)
    return table


CRC_TABLE = crc_table()


def crc32(data):
    # libvafs' crc.c: CRC-32, polynomial 0x04C11DB7, not reflected, starts at 0xFFFFFFFF, inverted
    value = 0xFFFFFFFF
    for byte in data:
        value = (value << 8 & 0xFFFFFFFF) ^ CRC_TABLE[(value >> 24 ^ byte) & 0xFF]
    return value ^ 0xFFFFFFFF


def position(offset):
    return struct.pack("<II", offset // BLOCK_SIZE, offset % BLOCK_SIZE)


class Writer:
    def __init__(self):
        self.descriptors = bytearray()
        self.data = bytearray()
        self.counts = [0, 0, 0]  # files, directories, symlinks

    def directory(self, entries):
        """Appends the entry list of a directory, subdirectories first, returns where it starts"""
        children = {name: self.directory(value) for name, value in entries.items() if isinstance(value, dict)}
        list_offset = len(self.descriptors)
        self.descriptors += struct.pack("<I", len(entries))
        for name, value in entries.items():
            encoded = name.encode()
            if isinstance(value, dict):
                self.counts[1] += 1
                self.descriptors += struct.pack("<HH", TYPE_DIRECTORY, 16 + len(encoded))
                self.descriptors += position(children[name]) + struct.pack("<I", 0o755) + encoded
            elif isinstance(value, tuple):
                self.counts[2] += 1
                target = value[1].encode()
                self.descriptors += struct.pack("<HHHH", TYPE_SYMLINK, 8 + len(encoded) + len(target),
                                                len(encoded), len(target)) + encoded + target
            else:
                self.counts[0] += 1
                self.descriptors += struct.pack("<HH", TYPE_FILE, 20 + len(encoded))
                self.descriptors += position(len(self.data)) + struct.pack("<II", len(value), 0o644) + encoded
                self.data += value
        return list_offset


def stream(linear, zstd):
    blocks, table = bytearray(), bytearray()
    for start in range(0, len(linear), BLOCK_SIZE):
        block = bytes(linear[start:start + BLOCK_SIZE])
        on_disk = block
        if zstd:
            on_disk = subprocess.run(["zstd", "-q", "-c"], input=block, capture_output=True, check=True).stdout
        table += struct.pack("<IIIHH", len(on_disk), 16 + len(blocks), crc32(block), 0, 0)
        blocks += on_disk
    count = len(table) // 16
    return struct.pack("<4I", STREAM_MAGIC, BLOCK_SIZE, 16 + len(blocks), count) + blocks + table


def main():
    kind, out = sys.argv[1], sys.argv[2]
    zstd = kind == "zstd"
    writer = Writer()
    root = writer.directory(tree())

    features = bytearray()
    feature_count = 1
    # overview: header, 4 bytes padding, uncompressed size, counts, 4 bytes padding
    features += OVERVIEW_GUID + struct.pack("<I4xQIII4x", 48, len(writer.data), *writer.counts)
    if zstd:
        feature_count += 1
        features += FILTER_GUID + struct.pack("<I", 20)

    descriptors = stream(writer.descriptors, zstd)
    data = stream(writer.data, zstd)
    descriptor_offset = 36 + len(features)
    data_offset = descriptor_offset + len(descriptors)
    header = struct.pack("<IIIHHIII", VAFS_MAGIC, VAFS_VERSION, 0x8664, feature_count, 0, 0,
                         descriptor_offset, data_offset) + position(root)
    with open(out, "wb") as f:
        f.write(header + features + descriptors + data)


if __name__ == "__main__":
    main()
